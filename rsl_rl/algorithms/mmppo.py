def _actor_ppo_enabled(
    *,
    teacher_enabled: bool,
    epoch: int,
    teacher_only_interval: int,
    teacher_supervising_intervals: int,
    critic_win_streak: int,
) -> bool:
    """Return whether the rollout policy must receive the PPO objective.

    Critic-readiness gating belongs to teacher/DAgger warm-up.  Applying it to
    ordinary PPO (``teacher_coef is None``) creates a deadlock: the actor never
    changes, while a critic trained on that fixed policy may never reach the
    explained-variance threshold that would unlock it.
    """

    if not teacher_enabled:
        return True
    critic_ready = (
        epoch > teacher_supervising_intervals and critic_win_streak >= 3
    )
    return epoch >= teacher_only_interval and critic_ready


def _fixed_expert_stage(
    *,
    iteration: int,
    bc_only_iterations: int,
    dagger_plateau_iterations: tuple[int, ...] = (),
    dagger_student_probs: tuple[float, ...] = (),
    dagger_linear_iterations: int = 0,
    dagger_student_start_prob: float = 0.0,
    dagger_student_end_prob: float = 1.0,
) -> tuple[str, float, int]:
    """Return the fixed-expert behavior stage and student intervention rate.

    ``bc`` executes the expert everywhere.  ``dagger`` either uses the legacy
    piecewise-constant plateaus or linearly increases the student execution
    probability over ``dagger_linear_iterations`` updates.  The two schedules
    are deliberately mutually exclusive so a run cannot silently combine
    their semantics.  ``rl`` executes only the student; PPO is never mixed
    with rewards generated by expert or blended actions.
    """

    if (
        iteration < 0
        or bc_only_iterations < 0
        or dagger_linear_iterations < 0
    ):
        raise ValueError("iteration counts must be non-negative")
    if len(dagger_plateau_iterations) != len(dagger_student_probs):
        raise ValueError(
            "DAgger plateau durations and student probabilities must align"
        )
    if any(duration <= 0 for duration in dagger_plateau_iterations):
        raise ValueError("DAgger plateau durations must be positive")
    if any(not 0.0 <= probability <= 1.0 for probability in dagger_student_probs):
        raise ValueError("DAgger student probabilities must lie in [0, 1]")
    if any(
        not 0.0 <= probability <= 1.0
        for probability in (
            dagger_student_start_prob,
            dagger_student_end_prob,
        )
    ):
        raise ValueError("linear DAgger student probabilities must lie in [0, 1]")
    if dagger_student_start_prob > dagger_student_end_prob:
        raise ValueError("linear DAgger student probability must be non-decreasing")
    if dagger_linear_iterations > 0 and dagger_plateau_iterations:
        raise ValueError("linear and plateau DAgger schedules are mutually exclusive")

    if iteration < bc_only_iterations:
        return "bc", 0.0, -1
    relative_iteration = iteration - bc_only_iterations
    if relative_iteration < dagger_linear_iterations:
        if dagger_linear_iterations == 1:
            student_probability = dagger_student_end_prob
        else:
            schedule_fraction = relative_iteration / (dagger_linear_iterations - 1)
            student_probability = dagger_student_start_prob + schedule_fraction * (
                dagger_student_end_prob - dagger_student_start_prob
            )
        return "dagger", float(student_probability), relative_iteration
    for plateau_index, (duration, probability) in enumerate(
        zip(dagger_plateau_iterations, dagger_student_probs)
    ):
        if relative_iteration < duration:
            return "dagger", float(probability), plateau_index
        relative_iteration -= duration
    return "rl", 1.0, -1


def _fixed_expert_actor_ppo_enabled(
    *,
    stage: str,
    require_critic_ready: bool,
    critic_win_streak: int,
) -> bool:
    """Enable PPO only on a fully student-executed rollout."""

    if stage not in {"bc", "dagger", "rl"}:
        raise ValueError(f"unknown fixed-expert stage: {stage}")
    if stage != "rl":
        return False
    return not require_critic_ready or critic_win_streak >= 3


def _fixed_expert_bc_loss(
    student_mean: torch.Tensor,
    expert_action: torch.Tensor,
    *,
    mode: str,
) -> torch.Tensor:
    """Action-space distillation loss over labels stored during collection."""

    if student_mean.shape != expert_action.shape:
        raise ValueError(
            "student and fixed-expert actions must have identical shapes, got "
            f"{tuple(student_mean.shape)} and {tuple(expert_action.shape)}"
        )
    target = expert_action.detach()
    if mode == "mse":
        return F.mse_loss(student_mean, target)
    if mode == "huber":
        return F.smooth_l1_loss(student_mean, target)
    raise ValueError("fixed-expert BC mode must be 'mse' or 'huber'")


def _add_optional_loss(
    total_loss: torch.Tensor,
    component_loss: torch.Tensor,
    *,
    coefficient: float,
    name: str,
) -> torch.Tensor:
    """Add a weighted objective without materializing zero gradients.

    Adam-family optimizers can update a parameter from momentum or decoupled
    weight decay even when its gradient tensor contains only zeros.  Returning
    ``total_loss`` unchanged for a disabled objective keeps unrelated modules
    genuinely frozen during strict action-BC pretraining.
    """

    if coefficient < 0.0:
        raise ValueError(f"{name} coefficient must be non-negative")
    if coefficient == 0.0:
        return total_loss
    return total_loss + coefficient * component_loss


def chunk_q_bootstrap_target(
    rewards: torch.Tensor,
    dones: torch.Tensor,
    bootstrap_value: torch.Tensor,
    gamma: float,
) -> torch.Tensor:
    """Return a reset-safe discounted target for one realized action chunk.

    ``rewards`` and ``dones`` use the physical-step axis first.  A terminal
    transition contributes its own reward, then masks all later rewards and the
    value bootstrap.  This utility is deliberately independent of PPO update
    wiring so the chunk-Q assignment can be calibrated before it affects the
    actor or state-value critic.
    """

    if rewards.shape != dones.shape:
        raise ValueError("chunk-Q rewards and dones must have identical shapes")
    if rewards.ndim < 1:
        raise ValueError("chunk-Q rewards require a physical-step axis")
    if bootstrap_value.shape != rewards.shape[1:]:
        raise ValueError(
            "chunk-Q bootstrap shape must match the non-time reward axes"
        )
    if not 0.0 <= gamma <= 1.0:
        raise ValueError("chunk-Q gamma must lie in [0, 1]")

    target = torch.zeros_like(bootstrap_value, dtype=rewards.dtype)
    discount = torch.ones_like(target)
    for step in range(rewards.shape[0]):
        target = target + discount * rewards[step]
        discount = discount * float(gamma) * (~dones[step].bool()).to(
            rewards.dtype
        )
    return target + discount * bootstrap_value.to(rewards.dtype)


